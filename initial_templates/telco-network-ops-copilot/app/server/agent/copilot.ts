/**
 * NOC Copilot chat agent (the floating dock).
 *
 * Tools:
 *   ask_data         — the Genie agent (Agent mode): network analytics over the governed telemetry (sites down, alarm
 *                      storms by router, dropped-call rate / KPI anomalies, impact, ticket MTTR) AND the Halcyon NOC
 *                      runbook documents (cited)
 *   find_incidents   — the live Lakebase incident queue for "what should I work next?"
 *
 * The per-incident triage itself is NOT a chat tool — it runs from the incident
 * workbench (services/triage.ts) so its root cause, plan and dispatch render as UI.
 */
